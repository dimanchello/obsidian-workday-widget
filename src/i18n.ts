export type Lang = 'ru' | 'en';

function getLang(): Lang {
    if (typeof document === 'undefined') return 'ru';
    const htmlLang = document.documentElement.lang || '';
    return htmlLang.startsWith('ru') ? 'ru' : 'en';
}


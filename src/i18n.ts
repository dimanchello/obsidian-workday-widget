export function t(key: string, params?: Record<string, string>, lang?: Lang): string {
    const currentLang = lang ?? getLang();
    const text = dict[currentLang]?.[key] ?? dict.ru[key] ?? key;
    if (params) {
        return text.replace(/\{(\w+)\}/g, (_, k: string) => params[k] ?? `{${k}}`);
    }
    return text;
}
